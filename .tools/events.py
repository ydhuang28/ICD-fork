"""Builds ICD's versions of vanilla event files.

ICD changes some vanilla events (flavour events that convert pops, the Reformation...). An event id
defined twice keeps its first definition, and vanilla's files load before a mod's own files, so the
changed copies have to replace vanilla's file at the same path. This script writes those files:
vanilla's file from the installed game, with ICD's version of each event swapped in.

    .tools/event_substitutes/<path under in_game/events>   ICD's versions of the events (edit these)
    .tools/event_substitutes/vanilla_hashes.json           what each vanilla event looked like when ICD's
                                                           version was last checked against it
    in_game/events/<same path>                             generated; don't edit

usage (from the mod folder):
    python .tools/events.py [--game GAME_DIR] build    write the files
    python .tools/events.py [--game GAME_DIR] check    exit 1 if a file is out of date
    python .tools/events.py [--game GAME_DIR] accept   record vanilla's current events as checked

`build` and `check` stop when vanilla changed an event since its last check: compare vanilla's new
version with ICD's, carry the change over to the file in event_substitutes/ if it applies, then
run `accept`. GAME_DIR is the folder holding in_game/ (default: two levels above this mod).
"""
import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

MOD = Path(__file__).resolve().parent.parent
SOURCES = MOD / ".tools" / "event_substitutes"
HASHES = SOURCES / "vanilla_hashes.json"
EVENT = re.compile(r"\s*([A-Za-z0-9_]+\.[0-9]+)\s*=\s*\{")


class Text:
    def __init__(self, path):
        raw = path.read_bytes()
        self.bom = raw.startswith(b"\xef\xbb\xbf")
        text = raw.decode("utf-8-sig")
        self.eol = "\r\n" if "\r\n" in text else "\n"
        self.lines = text.replace("\r\n", "\n").split("\n")

    def to_bytes(self, lines):
        data = self.eol.join(lines).encode("utf-8")
        return (b"\xef\xbb\xbf" + data) if self.bom else data


def code(line):
    return re.sub(r'"[^"]*"', '""', line).split("#", 1)[0]


def events(lines):
    """{id: (first, last)} for top-level events, in file order."""
    out, depth, start, key = {}, 0, None, None
    for i, line in enumerate(lines):
        c = code(line)
        if depth == 0 and start is None:
            m = EVENT.match(c)
            if m:
                key, start = m.group(1), i
        depth += c.count("{") - c.count("}")
        if start is not None and depth <= 0:
            out[key] = (start, i)
            start, depth = None, 0
    return out


def digest(lines):
    body = "\n".join(re.sub(r"\s+", " ", code(l)).strip() for l in lines)
    return hashlib.sha256(re.sub(r"\n+", "\n", body).strip().encode("utf-8")).hexdigest()[:16]


def generate(game):
    """{output path: bytes}, {event id: vanilla hash}, [problems]."""
    recorded = json.loads(HASHES.read_text(encoding="utf-8")) if HASHES.is_file() else {}
    outputs, hashes, problems = {}, {}, []
    for src in sorted(SOURCES.rglob("*.txt")):
        rel = src.relative_to(SOURCES).as_posix()
        vpath = game / "in_game" / "events" / rel
        if not vpath.is_file():
            problems.append(f"{rel}: the game no longer has in_game/events/{rel}")
            continue
        ours, theirs = Text(src), Text(vpath)
        mine, vanilla = events(ours.lines), events(theirs.lines)
        lines = list(theirs.lines)
        added = []
        for eid, (a, b) in sorted(vanilla.items(), key=lambda kv: -kv[1][0]):
            if eid not in mine:
                continue
            h = digest(theirs.lines[a:b + 1])
            hashes[eid] = h
            if recorded.get(eid) not in (None, h):
                problems.append(f"{eid}: vanilla changed it since ICD's version was checked (in_game/events/{rel})")
            s, e = mine[eid]
            lines[a:b + 1] = ours.lines[s:e + 1]
        for eid, (s, e) in mine.items():
            if eid not in vanilla:
                added += [""] + ours.lines[s:e + 1]
        replaced = sorted(set(mine) & set(vanilla), key=lambda k: (k.split(".")[0], int(k.split(".")[1])))
        header = [f"# Improved Culture Dynamics: the game's file with ICD's versions of {', '.join(replaced)}"
                  + (f", plus {', '.join(k for k in mine if k not in vanilla)}" if added else "") + ".",
                  f"# Generated by .tools/events.py from .tools/event_substitutes/{rel}. Edit that file, not this one."]
        outputs[MOD / "in_game" / "events" / rel] = theirs.to_bytes(header + lines + added)
    return outputs, hashes, problems


def lf(data):
    return data.replace(b"\r\n", b"\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--game", type=Path, default=MOD.parent.parent)
    ap.add_argument("command", choices=["build", "check", "accept"])
    args = ap.parse_args()
    if not (args.game / "in_game" / "events").is_dir():
        sys.exit(f"{args.game} has no in_game/events; pass --game")
    outputs, hashes, problems = generate(args.game)
    if args.command == "accept":
        HASHES.write_text(json.dumps(dict(sorted(hashes.items())), indent=1) + "\n", encoding="utf-8")
        print(f"recorded {len(hashes)} vanilla events")
        return
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    # git may check files out with either line ending
    stale = [p for p, data in outputs.items() if not p.is_file() or lf(p.read_bytes()) != lf(data)]
    if args.command == "check":
        for p in stale:
            print(f"out of date: {p.relative_to(MOD).as_posix()}")
        sys.exit(1 if stale else 0)
    for p in stale:
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_bytes(outputs[p])
        print(f"wrote {p.relative_to(MOD).as_posix()}")
    print(f"{len(outputs)} files, {len(stale)} rewritten")


if __name__ == "__main__":
    main()
